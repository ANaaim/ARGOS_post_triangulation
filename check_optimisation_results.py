from utils import choose_file
import numpy as np

def extract_optimization_info(npy_file):
    """
    Extract optimization information from a .npy file generated by the kinematics.py script.
    
    Parameters:
        npy_file (str or Path): Path to the .npy file containing optimization data.

    Returns:
        dict: A dictionary containing the optimization information.
    """
    data = np.load(npy_file, allow_pickle=True).item()
    return data.get("optim_information", {})

if __name__ == "__main__":
    import sys

    if len(sys.argv) > 1:
        npy_file = sys.argv[1]
    else:
        npy_file = choose_file()

    if npy_file:
        optim_info = extract_optimization_info(npy_file)
        print("Optimization Information:")
        print(optim_info)